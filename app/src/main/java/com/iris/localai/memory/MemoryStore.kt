/**
 * 记忆三库：日记、记忆库、知识库。
 * - 常规对话只注入精简摘要，不直接注入日记；
 * - 需要回忆时由 memory 工具或回忆意图触发 [recall]，做向量 + 关键词混合检索；
 * - 日记按应用实际打开过的日期自动生成，未打开的日子跳过。
 */
