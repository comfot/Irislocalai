    fun addDiary(entry: DiaryEntry) {
        val now = System.currentTimeMillis()
        _diary.update {
            (it + entry.copy(updatedAt = now)).sortedByDescending { item -> item.date }
        }
        persistDiary()
    }

    fun updateDiary(entry: DiaryEntry) {
        _diary.update { list ->
            list.map { if (it.id == entry.id) entry.copy(updatedAt = System.currentTimeMillis()) else it }
        }
        persistDiary()
    }

    fun deleteDiary(id: String) {
        _diary.update { list -> list.filterNot { it.id == id } }
        persistDiary()
    }

    fun addMemory(item: MemoryItem) {
        val now = System.currentTimeMillis()
        _memories.update {
            it + item.copy(
                createdAt = item.createdAt.takeIf { value -> value > 0L } ?: now,
                updatedAt = now,
            )
        }
        persistMemories()
        autoLinkFor(item)
    }

    fun updateMemory(item: MemoryItem) {
        _memories.update { list ->
            list.map {
                if (it.id == item.id) item.copy(updatedAt = System.currentTimeMillis()) else it
            }
        }
        persistMemories()
    }

    fun deleteMemory(id: String) {
        _memories.update { list -> list.filterNot { it.id == id } }
        _links.update { list -> list.filterNot { link -> link.sourceId == id || link.targetId == id } }
        persistMemories()
        persistLinks()
    }

    fun linkMemories(
        sourceId: String,
        targetId: String,
        type: String = "RELATED",
        weight: Float = 1f,
        description: String = "",
    ): MemoryLink? {
        if (sourceId == targetId) return null
        val ids = _memories.value.map { it.id }.toSet()
        if (sourceId !in ids || targetId !in ids) return null
        val normalizedType = type.trim().uppercase().ifBlank { "RELATED" }.take(48)
        val normalizedWeight = weight.coerceIn(0f, 1f)
        val existing = _links.value.firstOrNull {
            it.sourceId == sourceId && it.targetId == targetId && it.type == normalizedType
        }
        if (existing != null) {
            if (existing.weight != normalizedWeight || existing.description != description) {
                _links.update { list ->
                    list.map {
                        if (it.id == existing.id) {
                            it.copy(weight = normalizedWeight, description = description.take(240))
                        } else {
                            it
                        }
                    }
                }
                persistLinks()
            }
            return existing.copy(weight = normalizedWeight, description = description.take(240))
        }
        val link = MemoryLink(
            sourceId = sourceId,
            targetId = targetId,
            type = normalizedType,
            weight = normalizedWeight,
            description = description.take(240),
        )
        _links.update { it + link }
        persistLinks()
        return link
    }

    fun linkByTitle(
        sourceTitle: String,
        targetTitle: String,
        type: String = "RELATED",
        weight: Float = 1f,
        description: String = "",
    ): MemoryLink? {
        val source = findMemoryByTitle(sourceTitle) ?: return null
        val target = findMemoryByTitle(targetTitle) ?: return null
        return linkMemories(source.id, target.id, type, weight, description)
    }

    fun deleteLink(id: String) {
        _links.update { list -> list.filterNot { it.id == id } }
        persistLinks()
    }

    fun findMemoryByTitle(title: String): MemoryItem? {
        val wanted = title.trim()
        if (wanted.isBlank()) return null
        return _memories.value.firstOrNull { it.title.equals(wanted, ignoreCase = true) }
            ?: _memories.value.firstOrNull { it.content.equals(wanted, ignoreCase = true) }
    }

    /** 为单条记忆按共享标签/同文件夹补边，最多两条。 */
    private fun autoLinkFor(item: MemoryItem): Int {
        val candidates = _memories.value.filter { other ->
            other.id != item.id && other.enabled
        }
        var created = 0
        val tagMatches = candidates
            .map { other -> other to other.tags.count { tag -> item.tags.any { it.equals(tag, true) } } }
            .filter { it.second > 0 }
            .sortedByDescending { it.second }
            .take(2)
        tagMatches.forEach { (other, count) ->
            if (linkNew(
                    item.id,
                    other.id,
                    type = "SHARED_TAG",
                    weight = (0.35f + count * 0.1f).coerceAtMost(0.8f),
                    description = "共享标签",
                )
            ) {
                created += 1
            }
        }
        if (created == 0 && item.folder.isNotBlank()) {
            candidates
                .filter { it.folder == item.folder }
                .take(2)
                .forEach { other ->
                    if (linkNew(
                            item.id,
                            other.id,
                            type = "SAME_FOLDER",
                            weight = 0.3f,
                            description = "同一文件夹：${item.folder}",
                        )
                    ) {
                        created += 1
                    }
                }
        }
        return created
    }

    /** 为整库补边，返回新增关系数。 */
    fun autoLinkAll(limitPerMemory: Int = 2): Int {
        var created = 0
        _memories.value.filter { it.enabled }.forEach { item ->
            val candidates = _memories.value
                .filter { it.id != item.id && it.enabled }
            val tagMatches = candidates
                .map { other -> other to other.tags.count { tag -> item.tags.any { it.equals(tag, true) } } }
                .filter { it.second > 0 }
                .sortedByDescending { it.second }
                .take(limitPerMemory)
            var local = 0
            tagMatches.forEach { (other, count) ->
                if (linkNew(
                        item.id,
                        other.id,
                        type = "SHARED_TAG",
                        weight = (0.35f + count * 0.1f).coerceAtMost(0.8f),
                        description = "自动关联：共享标签",
                    )
                ) {
                    local += 1
                    created += 1
                }
            }
            if (local == 0 && item.folder.isNotBlank()) {
                candidates.filter { it.folder == item.folder }.take(limitPerMemory).forEach { other ->
                    if (linkNew(
                            item.id,
                            other.id,
                            type = "SAME_FOLDER",
                            weight = 0.3f,
                            description = "自动关联：同一文件夹",
                        )
                    ) {
                        created += 1
                    }
                }
            }
        }
        return created
    }

    private fun linkNew(
        sourceId: String,
        targetId: String,
        type: String,
        weight: Float,
        description: String,
    ): Boolean {
        val exists = _links.value.any {
            (it.sourceId == sourceId && it.targetId == targetId) ||
                (it.sourceId == targetId && it.targetId == sourceId)
        }
        if (exists) return false
        return linkMemories(sourceId, targetId, type, weight, description) != null
    }

    fun memoryGraph(folder: String? = null): MemoryGraphData {
        val memories = _memories.value.filter {
            folder.isNullOrBlank() || it.folder.ifBlank { UNCATEGORIZED } == folder
        }
        val nodes = memories.map { item ->
            MemoryGraphNode(
                memoryId = item.id,
                label = item.title.ifBlank { item.content.take(18) },
                folder = item.folder.ifBlank { UNCATEGORIZED },
                enabled = item.enabled,
            )
        }
        val ids = nodes.map { it.memoryId }.toSet()
        return MemoryGraphData(
            nodes = nodes,
            edges = _links.value.filter { it.sourceId in ids && it.targetId in ids },
        )
    }

