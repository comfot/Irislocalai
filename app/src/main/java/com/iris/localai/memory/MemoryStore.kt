    /** 供记忆库搜索框与文件夹筛选使用的轻量过滤，不触发向量计算。 */
    fun filterMemories(query: String = "", folder: String? = null): List<MemoryItem> {
        val tokens = queryTokens(query)
        return _memories.value
            .asSequence()
            .filter { folder.isNullOrBlank() || it.folder.ifBlank { UNCATEGORIZED } == folder }
            .filter { item ->
                tokens.isEmpty() || tokens.any { token ->
                    item.title.contains(token, ignoreCase = true) ||
                        item.content.contains(token, ignoreCase = true) ||
                        item.folder.contains(token, ignoreCase = true) ||
                        item.tags.any { tag -> tag.contains(token, ignoreCase = true) }
                }
            }
            .sortedWith(compareByDescending<MemoryItem> { it.importance }.thenByDescending { it.updatedAt })
            .toList()
    }

    fun memoryFolders(): List<String> = _memories.value
        .map { it.folder.ifBlank { UNCATEGORIZED } }
        .distinct()
        .sorted()

    fun searchKnowledge(query: String): List<KnowledgeDocument> {
        val tokens = queryTokens(query)
        if (tokens.isEmpty()) return _knowledge.value.filter { it.enabled }
        return _knowledge.value
            .filter { it.enabled }
            .filter { doc ->
                tokens.any { token ->
                    doc.title.contains(token, ignoreCase = true) ||
                        doc.content.contains(token, ignoreCase = true) ||
                        doc.tags.any { tag -> tag.contains(token, ignoreCase = true) }
                }
            }
            .sortedByDescending { doc -> scoreKnowledge(doc, tokens) }
    }

    /** 常规注入：只给精简摘要和知识索引，不包含日记全文。 */
    fun briefContext(
        includeMemory: Boolean = true,
        includeKnowledge: Boolean = true,
        maxChars: Int = 420,
    ): String {
        val blocks = mutableListOf<String>()
        val enabledMemories = _memories.value.filter { it.enabled && it.content.isNotBlank() }

        if (includeMemory && enabledMemories.isNotEmpty()) {
            val top = enabledMemories
                .sortedByDescending { digestScore(it) }
                .take(6)
            val themes = enabledMemories
                .flatMap { it.tags }
                .filter { it.isNotBlank() }
                .groupingBy { it }
                .eachCount()
                .entries
                .sortedByDescending { it.value }
                .take(3)
                .map { it.key }
            val folders = enabledMemories
                .map { it.folder.ifBlank { UNCATEGORIZED } }
                .distinct()
                .take(3)
            blocks += buildString {
                appendLine("记忆摘要（共 ${enabledMemories.size} 条，细节按需回忆）：")
                if (themes.isNotEmpty()) appendLine("主题：${themes.joinToString("、")}")
                if (folders.isNotEmpty()) appendLine("文件夹：${folders.joinToString("、")}")
                top.forEach { item ->
                    val title = item.title.ifBlank { item.content.take(18) }
                    appendLine("- 【${item.type.label}】$title：${item.content.take(70)}")
                }
            }.trim()
        }

        if (includeKnowledge) {
            val docs = _knowledge.value
                .filter { it.enabled && it.title.isNotBlank() }
                .sortedByDescending { it.updatedAt }
                .take(4)
            if (docs.isNotEmpty()) {
                blocks += "知识库索引：\n" + docs.joinToString("\n") { doc ->
                    val tags = doc.tags.take(3).joinToString("、")
                    "- ${doc.title}${if (tags.isBlank()) "" else "（$tags）"}：${doc.content.take(60)}"
                }
            }
        }
        return fitBudget(blocks, maxChars)
    }

    /** 供记忆页展示的摘要文本。 */
    fun digestText(maxChars: Int = 900): String =
        briefContext(includeMemory = true, includeKnowledge = false, maxChars = maxChars)

    /**
     * 详细回忆：记忆库 + 知识库 +（可选）日记。
     * 优先使用配置的 Embedding 角色，未配置或失败时回退本地哈希向量。
     */
    suspend fun recall(
        query: String,
        limit: Int = 6,
        includeDiary: Boolean = true,
        includeKnowledge: Boolean = true,
    ): MemoryRecallResult = withContext(Dispatchers.IO) {
        val cleanQuery = query.trim()
        val wanted = limit.coerceIn(1, 20)
        val candidates = recallCandidates(includeDiary, includeKnowledge)
        if (candidates.isEmpty()) {
            return@withContext MemoryRecallResult(cleanQuery, "none", emptyList())
        }
        if (cleanQuery.isBlank()) {
            val hits = candidates
                .sortedByDescending { salience(it) }
                .take(wanted)
                .map { it.toHit(it.importance) }
            return@withContext MemoryRecallResult(cleanQuery, "salience", hits)
        }

        val queryVector = run {
            var vector = embeddingClient?.embed(cleanQuery)
                ?: MemoryVector(HashEmbedding.KEY, HashEmbedding.embed(cleanQuery))
            if (vector.key != HashEmbedding.KEY) {
                val missing = candidates.filter { cachedVector(it, vector.key) == null }
                if (missing.isNotEmpty()) {
                    val batch = embeddingClient?.embedBatch(missing.map { it.text })
                    if (batch == null) {
                        vector = MemoryVector(HashEmbedding.KEY, HashEmbedding.embed(cleanQuery))
                    } else {
                        missing.forEachIndexed { index, candidate ->
                            val values = batch.getOrNull(index)
                                ?.takeIf { it.key == vector.key }
                                ?.values
                            if (values != null) {
                                vectorCache[candidate.id] = CachedVector(
                                    vector.key,
                                    candidate.text.hashCode(),
                                    values,
                                )
                            }
                        }
                    }
                }
            }
            vector
        }
        val tokens = queryTokens(cleanQuery)
        val scored = candidates.map { candidate ->
            val vector = if (queryVector.values.isEmpty()) {
                null
            } else {
                vectorFor(candidate, queryVector.key)
            }
            val semantic = if (vector == null) 0f else {
                HashEmbedding.cosine(queryVector.values, vector).coerceIn(0f, 1f)
            }
            val lexical = lexicalScore(candidate, tokens)
            val score = if (vector != null) {
                semantic * 0.6f + lexical * 0.3f + salience(candidate) * 0.1f
            } else {
                lexical * 0.8f + salience(candidate) * 0.2f
            }
            candidate to score
        }.sortedByDescending { it.second }

        val top = scored.take(wanted)
        val now = System.currentTimeMillis()
        val memoryIds = top.mapNotNull { (candidate, _) ->
            candidate.id.takeIf { candidate.kind == RecallKind.MEMORY }
        }.toSet()
        if (memoryIds.isNotEmpty()) {
            _memories.update { list ->
                list.map { if (it.id in memoryIds) it.copy(lastAccessedAt = now) else it }
            }
            persistMemories()
        }
        MemoryRecallResult(
            query = cleanQuery,
            vectorMode = queryVector.key,
            hits = top.map { (candidate, score) -> candidate.toHit(score) },
        )
    }

    fun formatRecall(result: MemoryRecallResult): String {
        if (result.hits.isEmpty()) {
            return if (result.query.isBlank()) "记忆库为空" else "没有找到与「${result.query}」相关的记忆"
        }
        return buildString {
            appendLine("详细回忆（${result.vectorMode}）：${result.query.ifBlank { "最近记忆" }}")
            result.hits.forEach { hit ->
                val date = if (hit.date.isBlank()) "" else "${hit.date} "
                appendLine("- 【${hit.kind.label}】$date${hit.title.ifBlank { "未命名" }}：${hit.content.take(260)}")
            }
        }.trimEnd()
    }

    /** 兼容旧调用：只返回摘要，不再把查询词直接拼进常驻提示。 */
    fun promptContext(
        query: String,
        maxChars: Int = 2400,
        includeMemory: Boolean = true,
        includeKnowledge: Boolean = true,
    ): String = briefContext(includeMemory, includeKnowledge, maxChars)

    /**
     * 记录今天打开过应用；只对“打开过且没有日记”的过去日期生成日记。
     * 未打开的日子不在 usageDays 中，因此会自然跳过。
     */
    fun onAppOpened(autoDiary: Boolean) {
        val today = LocalDate.now().toString()
        if (usageDays.add(today)) {
            persistDateSet(usageFile, usageDays)
        }
        if (autoDiary) {
            scope.launch { generateMissingDiaries() }
        }
    }

    suspend fun generateMissingDiaries(): Int = withContext(Dispatchers.IO) {
        diaryMutex.withLock {
            val today = LocalDate.now()
            val existingDates = _diary.value.map { it.date }.toSet()
            val candidates = usageDays
                .toList()
                .filter { raw ->
                    val date = runCatching { LocalDate.parse(raw) }.getOrNull()
                    date != null && date.isBefore(today)
                }
                .filter { it !in existingDates && it !in handledDiaryDays }
                .sorted()
                .takeLast(MAX_DIARY_DAYS)
            var created = 0
            candidates.forEach { date ->
                val entry = runCatching { buildDiary(date) }.getOrNull()
                handledDiaryDays += date
                if (entry != null) {
                    _diary.update { list ->
                        (list + entry).sortedByDescending { item -> item.date }
                    }
                    created += 1
                }
            }
            persistDateSet(handledFile, handledDiaryDays)
            if (created > 0) persistDiary()
            created
        }
    }

    fun looksLikeRecall(text: String): Boolean = RECALL_PATTERN.containsMatchIn(text)

    private fun recallCandidates(
        includeDiary: Boolean,
        includeKnowledge: Boolean,
    ): List<RecallCandidate> = buildList {
        _memories.value
            .filter { it.enabled && it.content.isNotBlank() }
            .forEach { item ->
                add(
                    RecallCandidate(
                        kind = RecallKind.MEMORY,
                        id = item.id,
                        title = item.title.ifBlank { item.content.take(18) },
                        content = item.content,
                        date = "",
                        tags = item.tags,
                        importance = ((item.importance.coerceIn(1, 5) - 1) / 4f),
                        updatedAt = item.updatedAt,
                        text = buildString {
                            appendLine(item.title)
                            appendLine(item.folder)
                            appendLine(item.content)
                            appendLine(item.tags.joinToString(" "))
                        },
                    ),
                )
            }
        if (includeDiary) {
            _diary.value.forEach { entry ->
                add(
                    RecallCandidate(
                        kind = RecallKind.DIARY,
                        id = entry.id,
                        title = entry.title.ifBlank { "日记" },
                        content = entry.content,
                        date = entry.date,
                        tags = entry.tags,
                        importance = 0.45f,
                        updatedAt = entry.updatedAt,
                        text = "${entry.date} ${entry.title} ${entry.content} ${entry.tags.joinToString(" ")}",
                    ),
                )
            }
        }
        if (includeKnowledge) {
            _knowledge.value
                .filter { it.enabled && it.content.isNotBlank() }
                .forEach { doc ->
                    add(
                        RecallCandidate(
                            kind = RecallKind.KNOWLEDGE,
                            id = doc.id,
                            title = doc.title,
                            content = doc.content,
                            date = "",
                            tags = doc.tags,
                            importance = 0.5f,
                            updatedAt = doc.updatedAt,
                            text = "${doc.title} ${doc.content} ${doc.tags.joinToString(" ")}",
                        ),
                    )
                }
        }
    }

    private suspend fun vectorFor(candidate: RecallCandidate, key: String): FloatArray? {
        val textHash = candidate.text.hashCode()
        val cached = vectorCache[candidate.id]
        if (cached != null && cached.key == key && cached.textHash == textHash) {
            return cached.values
        }
        if (key != HashEmbedding.KEY) return null
        val values = HashEmbedding.embed(candidate.text)
        vectorCache[candidate.id] = CachedVector(key, textHash, values)
        return values
    }

    private fun cachedVector(candidate: RecallCandidate, key: String): FloatArray? {
        val cached = vectorCache[candidate.id] ?: return null
        return cached.values.takeIf {
            cached.key == key && cached.textHash == candidate.text.hashCode()
        }
    }

    private fun lexicalScore(candidate: RecallCandidate, tokens: List<String>): Float {
        if (tokens.isEmpty()) return 0f
        val title = candidate.title.lowercase()
        val body = (candidate.content + " " + candidate.tags.joinToString(" ")).lowercase()
        val hits = tokens.count { token -> title.contains(token) || body.contains(token) }
        val titleHits = tokens.count { token -> title.contains(token) }
        return ((hits.toFloat() / tokens.size) * 0.7f + (titleHits.toFloat() / tokens.size) * 0.3f)
            .coerceIn(0f, 1f)
    }

    private fun salience(candidate: RecallCandidate): Float {
        val recency = recencyScore(candidate.updatedAt)
        return candidate.importance * 0.65f + recency * 0.35f
    }

    private fun digestScore(item: MemoryItem): Float {
        val importance = (item.importance.coerceIn(1, 5) - 1) / 4f
        val accessed = recencyScore(item.lastAccessedAt)
        val updated = recencyScore(item.updatedAt)
        return importance * 0.5f + updated * 0.3f + accessed * 0.2f
    }

    private fun buildDiary(date: String): DiaryEntry? {
        val store = conversations ?: return null
        val day = runCatching { LocalDate.parse(date) }.getOrNull() ?: return null
        val zone = ZoneId.systemDefault()
        val start = day.atStartOfDay(zone).toInstant().toEpochMilli()
        val end = day.plusDays(1).atStartOfDay(zone).toInstant().toEpochMilli()
        val dayMessages = store.conversations.value.flatMap { conversation ->
            conversation.messages.mapNotNull { message ->
                if (message.createdAt in start until end && message.text.isNotBlank()) {
                    conversation to message
                } else {
                    null
                }
            }
        }
        val newMemories = _memories.value.filter { it.createdAt in start until end }
        if (dayMessages.isEmpty() && newMemories.isEmpty()) return null

        val userMessages = dayMessages.filter { it.second.role == ChatRole.USER }.map { it.second }
        val assistantMessages = dayMessages.filter { it.second.role == ChatRole.ASSISTANT }.map { it.second }
        val spaces = dayMessages.map { it.first.space.label }.distinct()
        val topics = userMessages
            .map { cleanText(it.text) }
            .filter { it.isNotBlank() }
            .distinct()
            .take(3)
        val lastReply = assistantMessages
            .lastOrNull()
            ?.let { runCatching { AssistantMessageParser.mainText(it.text) }.getOrDefault(it.text) }
            ?.let { cleanText(it) }
            ?.take(160)
            .orEmpty()
        val memoryLines = newMemories
            .take(3)
            .map { item -> cleanText(item.title.ifBlank { item.content }).take(80) }
        val title = topics.firstOrNull()?.take(20).orEmpty().ifBlank { "日常记录" }
        val mood = moodOf(dayMessages.joinToString(" ") { it.second.text + " " + it.second.reasoning })
        val content = buildString {
            appendLine("这一天在 ${spaces.ifEmpty { listOf("聊天") }.joinToString("、")} 里留下 ${userMessages.size} 轮对话。")
            if (topics.isNotEmpty()) appendLine("聊到：${topics.joinToString("；")}")
            if (lastReply.isNotBlank()) appendLine("最后：$lastReply")
            if (memoryLines.isNotEmpty()) appendLine("新记住：${memoryLines.joinToString("；")}")
            append("自动整理，省略了细节。")
        }.trim()
        return DiaryEntry(
            date = date,
            title = title,
            content = content,
            mood = mood,
            tags = spaces.take(4),
            autoGenerated = true,
        )
    }

    private fun moodOf(text: String): String {
        if (text.isBlank()) return "平静"
        val positive = POSITIVE_WORDS.count { text.contains(it) }
        val negative = NEGATIVE_WORDS.count { text.contains(it) }
        return when {
            positive > negative + 1 -> "愉悦"
            negative > positive + 1 -> "低落"
            positive > 0 || negative > 0 -> "起伏"
            else -> "平静"
        }
    }

    private fun cleanText(text: String): String = text
        .replace(Regex("[\\r\\n]+"), " ")
        .replace(Regex("\\s+"), " ")
        .trim()

    private fun scoreKnowledge(doc: KnowledgeDocument, tokens: List<String>): Float {
        val title = doc.title.lowercase()
        val content = doc.content.lowercase()
        val tags = doc.tags.joinToString(" ").lowercase()
        val hits = tokens.count { token ->
            title.contains(token) || content.contains(token) || tags.contains(token)
        }
        val relevance = hits.toFloat() / tokens.size
        return relevance * 0.75f + recencyScore(doc.updatedAt) * 0.25f
    }

    private fun queryTokens(query: String): List<String> {
        val parts = query.lowercase()
            .split(Regex("[\\s,，。.;；:：!！?？|]+"))
            .filter { it.length >= 2 }
        val han = query.filter { it.code in 0x4E00..0x9FFF }
        val ngrams = buildList {
            if (han.length == 1) {
                add(han)
            } else {
                for (index in han.indices) {
                    if (index + 1 < han.length) add(han.substring(index, index + 2))
                    if (index + 2 < han.length) add(han.substring(index, index + 3))
                }
            }
        }
        return (parts + ngrams).distinct().take(48)
    }

    private fun recencyScore(timestamp: Long): Float {
        if (timestamp <= 0L) return 0f
        val ageDays = ((System.currentTimeMillis() - timestamp).coerceAtLeast(0L)) / DAY_MS.toFloat()
        return 0.5.pow((ageDays / HALF_LIFE_DAYS).toDouble()).toFloat().coerceIn(0f, 1f)
    }

    private fun fitBudget(blocks: List<String>, maxChars: Int): String {
        var budget = maxChars.coerceAtLeast(120)
        val kept = mutableListOf<String>()
        for (block in blocks) {
            if (budget <= 0) break
            val text = if (block.length <= budget) block else block.take(budget)
            kept += text
            budget -= text.length + 2
        }
        return kept.joinToString("\n\n").trim()
    }

