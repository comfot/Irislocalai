@Composable
internal fun VrmaGenerationDialog(
    onDismiss: () -> Unit,
) {
    val context = LocalContext.current
    val graph = remember(context) { (context.applicationContext as IrisApp).graph }
    val environment = remember { graph.vrmaGeneration }
    val store = remember { graph.vrmaMotions }
    val scope = rememberCoroutineScope()
    var prompt by rememberSaveable { mutableStateOf("") }
    var duration by rememberSaveable { mutableStateOf("3") }
    var status by remember { mutableStateOf<String?>(null) }
    var busy by remember { mutableStateOf(false) }
    var previewUrl by remember { mutableStateOf<String?>(null) }
    var generated by remember { mutableStateOf<List<PendingVrma>>(emptyList()) }
    var renameTarget by remember { mutableStateOf<PendingVrma?>(null) }
    var renameText by rememberSaveable { mutableStateOf("") }
    var closed by remember { mutableStateOf(false) }
    val latestPending = rememberUpdatedState(generated)
    val model = remember { graph.characterModels.boundModel(graph.settings.current.characterId) ?: graph.characterModels.active() }
    val modelFile: File? = remember(model?.id) {
        model?.takeIf { it.type == CharacterModelType.VRM || it.type == CharacterModelType.GLB }
            ?.let { graph.storage.modelFile("character_models", it.directory, it.entryFile) }
    }

    fun close() {
        closed = true
        generated.forEach(environment::deletePending)
        generated = emptyList()
        onDismiss()
    }

    DisposableEffect(Unit) {
        onDispose {
            latestPending.value.forEach(environment::deletePending)
        }
    }

    fun generate() {
        if (busy || prompt.isBlank()) return
        busy = true
        status = "正在启动服务并生成…"
        scope.launch {
            val result = runCatching {
                environment.generatePending(prompt, duration.toDoubleOrNull() ?: 0.0)
            }
            result.onSuccess { pending ->
                if (closed) {
                    environment.deletePending(pending)
                    return@onSuccess
                }
                generated = (listOf(pending) + generated).distinctBy { it.id }
                previewUrl = pending.previewUrl()
                MotionBridge.playVrma(previewUrl!!, holdIdle = pending.displayName.contains("坐"))
                status = "已生成临时动作：${pending.displayName}"
            }.onFailure { status = it.message ?: "生成失败" }
            busy = false
        }
    }

    fun save(target: PendingVrma, name: String) {
        val clean = name.trim().ifBlank { target.displayName }
        val result = runCatching {
            environment.savePending(target, clean)
        }
        result.onSuccess { asset ->
            graph.motionBindings.ensureActions(Model3DKind.VRM, listOf(asset.name))
            graph.motionBindings.bind(Model3DKind.VRM, asset.name, asset.name)
            generated = generated.filterNot { it.id == target.id }
            previewUrl = store.virtualUrl(asset)
            MotionBridge.playVrma(previewUrl!!, holdIdle = asset.name.contains("坐"))
            status = "已保存到动作：${asset.name}"
            renameTarget = null
        }.onFailure {
            status = it.message ?: "保存失败"
        }
    }

    Dialog(
        onDismissRequest = ::close,
        properties = DialogProperties(usePlatformDefaultWidth = false),
    ) {
        Surface(
            modifier = Modifier.fillMaxWidth(0.96f).fillMaxSize(0.92f),
            shape = RoundedCornerShape(20.dp),
            color = MaterialTheme.colorScheme.surface,
            tonalElevation = 6.dp,
        ) {
            Column(modifier = Modifier.fillMaxSize().padding(16.dp)) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Column(modifier = Modifier.weight(1f)) {
                        Text("VRMA动作生成", style = MaterialTheme.typography.titleMedium)
                        Text(
                            "使用 Text-To-VRMA 与当前语言模型提供商生成 VRMA",
                            style = MaterialTheme.typography.labelSmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                        )
                    }
                    IconButton(onClick = { scope.launch { status = environment.start() } }, enabled = !busy) {
                        Icon(Icons.Outlined.Refresh, contentDescription = "启动或刷新服务")
                    }
                    IconButton(onClick = ::close) {
                        Icon(Icons.Outlined.Close, contentDescription = "关闭")
                    }
                }
                Spacer(Modifier.height(8.dp))
                Box(
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(250.dp)
                        .padding(vertical = 4.dp),
                    contentAlignment = Alignment.Center,
                ) {
                    if (modelFile != null) {
                        CharacterModel3DView(
                            modelFile = modelFile,
                            modelType = model?.type?.name.orEmpty(),
                            accentHex = null,
                            dark = false,
                            interactive = false,
                            motionIdle = false,
                            modelRoot = "character_models",
                            previewVrmaUrl = previewUrl,
                            modifier = Modifier.fillMaxSize(),
                        )
                    } else {
                        Text(
                            "需要为当前角色绑定 VRM/GLB 模型才能预览",
                            style = MaterialTheme.typography.bodySmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                        )
                    }
                }
                OutlinedTextField(
                    value = prompt,
                    onValueChange = { prompt = it.take(4000) },
                    modifier = Modifier.fillMaxWidth(),
                    label = { Text("动作描述，例如：开心地挥手打招呼") },
                    minLines = 2,
                    maxLines = 4,
                )
                Spacer(Modifier.height(6.dp))
                Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    OutlinedTextField(
                        value = duration,
                        onValueChange = { duration = it.filter(Char::isDigit).take(2) },
                        modifier = Modifier.width(96.dp),
                        label = { Text("秒") },
                        singleLine = true,
                    )
                    Button(
                        onClick = ::generate,
                        enabled = !busy && prompt.isNotBlank(),
                    ) { Text(if (busy) "生成中…" else "生成") }
                    TextButton(onClick = ::close) { Text("关闭") }
                }
                status?.let {
                    Text(
                        text = it,
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.primary,
                        maxLines = 2,
                        overflow = TextOverflow.Ellipsis,
                    )
                }
                Spacer(Modifier.height(8.dp))
                Text("本次生成（未保存，退出时删除）", style = MaterialTheme.typography.labelSmall)
                LazyColumn(modifier = Modifier.weight(1f)) {
                    items(generated, key = { it.id }) { pending ->
                        Row(
                            modifier = Modifier.fillMaxWidth().padding(vertical = 2.dp),
                            verticalAlignment = Alignment.CenterVertically,
                        ) {
                            Column(modifier = Modifier.weight(1f)) {
                                Text(pending.displayName, style = MaterialTheme.typography.bodySmall, maxLines = 1, overflow = TextOverflow.Ellipsis)
                                Text(
                                    "${pending.sizeBytes / 1024} KB",
                                    style = MaterialTheme.typography.labelSmall,
                                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                                )
                            }
                            IconButton(
                                onClick = {
                                    renameTarget = pending
                                    renameText = pending.displayName
                                },
                            ) {
                                Icon(Icons.Outlined.BookmarkAdd, contentDescription = "保存到动作")
                            }
                            IconButton(
                                onClick = {
                                    previewUrl = pending.previewUrl()
                                    MotionBridge.playVrma(previewUrl!!, holdIdle = pending.displayName.contains("坐"))
                                },
                            ) {
                                Icon(Icons.Outlined.PlayArrow, contentDescription = "播放")
                            }
                        }
                    }
                }
            }
        }
    }

    renameTarget?.let { target ->
        AlertDialog(
            onDismissRequest = { renameTarget = null },
            title = { Text("保存到动作") },
            text = {
                OutlinedTextField(
                    value = renameText,
                    onValueChange = { renameText = it.take(80) },
                    label = { Text("动作名称") },
                    singleLine = true,
                )
            },
            confirmButton = {
                TextButton(
                    onClick = { save(target, renameText) },
                    enabled = renameText.isNotBlank(),
                ) { Text("保存") }
            },
            dismissButton = {
                TextButton(onClick = { renameTarget = null }) { Text("取消") }
            },
        )
    }
}
